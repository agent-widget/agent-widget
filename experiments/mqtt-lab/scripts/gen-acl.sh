#!/usr/bin/env bash
# Regenerate broker/state/acl.conf from broker/acl.template.conf plus one
# `user <deviceId>` block per known device with exactly the cohort topics that
# device may subscribe to: its canary hash bucket + stable, plus any extra
# groups declared in broker/state/device-extra-groups.conf
# (one line per device: "<deviceId> <group> [group...]", created by
#  scripts/add-device-user.sh <id> <group...>).
#
# Called by scripts/start-broker.sh and scripts/add-device-user.sh. The
# rendered file is gitignored (broker/state/).
set -euo pipefail

LAB_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$LAB_ROOT"
mkdir -p broker/state

python3 - "$LAB_ROOT" > broker/state/acl.conf <<'PY'
import os
import sys

lab = sys.argv[1]
sys.path.insert(0, f"{lab}/sims")
import common  # FLEET + canary_bucket (stdlib only)

with open(f"{lab}/broker/acl.template.conf") as f:
    print(f.read(), end="")

extra = {}  # deviceId -> [groups]
extra_file = os.path.join(lab, "broker", "state", "device-extra-groups.conf")
if os.path.exists(extra_file):
    with open(extra_file) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            extra[parts[0]] = parts[1:]

devices = list(common.FLEET)
for dev in sorted(set(devices) | set(extra)):
    if dev not in devices:
        devices.append(dev)

print("\n# ---- per-device cohort ACLs (generated by scripts/gen-acl.sh) ----")
for dev in devices:
    groups = [f"canary-{common.canary_bucket(dev)}", "stable"] + extra.get(dev, [])
    print(f"user {dev}")
    for g in groups:
        print(f"topic read ota/group/{g}")
    print()
print(f"# fleet: {len(devices)} devices")
PY

echo ">> generated broker/state/acl.conf ($(wc -l < broker/state/acl.conf) lines)"
