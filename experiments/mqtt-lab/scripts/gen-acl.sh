#!/usr/bin/env bash
# Regenerate broker/state/acl.conf from broker/acl.template.conf plus one
# `user <deviceId>` block per KNOWN device with exactly the cohort topics that
# device may subscribe to: its canary hash bucket + stable, plus any extra
# groups declared in broker/state/device-extra-groups.conf
# (one line per device: "<deviceId> <group> [group...]", written by
#  scripts/add-device-user.sh <id> <group...>).
#
# The authoritative device inventory is broker/state/device-creds.env (every
# provisioned device has a line there) UNION the default fleet; a device only
# listed in the extra-groups file is also rendered.
#
# Called by scripts/start-broker.sh and scripts/add-device-user.sh. The
# rendered file is gitignored (broker/state/).
set -euo pipefail

LAB_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$LAB_ROOT"
mkdir -p broker/state

python3 - "$LAB_ROOT" > broker/state/acl.conf <<'PY'
import os
import re
import sys

lab = sys.argv[1]
sys.path.insert(0, f"{lab}/sims")
import common  # FLEET + canary_bucket (stdlib only)

# --- authoritative device inventory --------------------------------------
devices = set(common.FLEET)
creds_file = os.path.join(lab, "broker", "state", "device-creds.env")
if os.path.exists(creds_file):
    with open(creds_file) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                dev = line.partition("=")[0].strip()
                if re.fullmatch(r"[A-Za-z0-9_-]+", dev):
                    devices.add(dev)

extra = {}  # deviceId -> [groups]
extra_file = os.path.join(lab, "broker", "state", "device-extra-groups.conf")
if os.path.exists(extra_file):
    with open(extra_file) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            dev = parts[0]
            if re.fullmatch(r"[A-Za-z0-9_-]+", dev):
                extra[dev] = [g for g in parts[1:]
                              if re.fullmatch(r"[A-Za-z0-9_-]+", g)]
                devices.add(dev)

# --- render ---------------------------------------------------------------
with open(f"{lab}/broker/acl.template.conf") as f:
    print(f.read(), end="")

print("\n# ---- per-device cohort ACLs (generated by scripts/gen-acl.sh) ----")
for dev in sorted(devices):
    groups = [f"canary-{common.canary_bucket(dev)}", "stable"] + extra.get(dev, [])
    print(f"user {dev}")
    for g in groups:
        print(f"topic read ota/group/{g}")
    print()
print(f"# fleet: {len(devices)} devices")
PY

echo ">> generated broker/state/acl.conf ($(wc -l < broker/state/acl.conf) lines, devices: $(grep -c '^user esp32s3' broker/state/acl.conf))"
